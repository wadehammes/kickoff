#!/usr/bin/env bash
set -euo pipefail

# PreToolUse (Edit|Write): deny hand-edits to generated Contentful types.
# src/contentful/types/ is produced by `pnpm types:contentful`.

input="$(cat)"
file="$(printf '%s' "$input" | jq -r '.tool_input.file_path // ""')"

case "$file" in
  */src/contentful/types/* | src/contentful/types/*) ;;
  *) exit 0 ;;
esac

reason="Blocked: src/contentful/types/ is generated by \`pnpm types:contentful\` and must not be hand-edited. If a CMS content type changed, the user regenerates the types, then you update the consumers. See docs/handbook/contentful.md."

jq -n --arg r "$reason" '{
  hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "deny",
    permissionDecisionReason: $r
  }
}'

exit 0
